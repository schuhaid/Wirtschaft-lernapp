/** Kleinschreibung, Umlaute, Satzzeichen, Zahlwörter → Ziffern, Endungen weg */
export function canon(s: string): string {
  return s
    .toLowerCase()
    .replace(/:innen|\*innen|_innen|innen\b/g, "")
    .replace(/ä/g, "ae").replace(/ö/g, "oe").replace(/ü/g, "ue").replace(/ß/g, "ss")
    .replace(/[^a-z0-9 ]/g, " ")
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => NUM[w] ?? w)
    .map((w) => (w.length > 4 ? w.replace(/(en|er|es|em|e|n|s)$/, "") : w))
    .join(" ");
}

const INDEX = new Map<string, string[]>();
for (const g of SYNONYM_GROUPS) {
  const key = canon(g[0]);
  INDEX.set(key, [...(INDEX.get(key) ?? []), ...g.slice(1)]);
}

/** Gleichbedeutende Alternativen zu einem Lösungswort */
export function synonymsFor(word: string): string[] {
  return [...new Set(INDEX.get(canon(word)) ?? [])].filter((w) => canon(w) !== canon(word));
}
